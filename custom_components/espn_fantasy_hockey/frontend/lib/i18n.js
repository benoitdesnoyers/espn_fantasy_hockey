/** The user's language code ("en", "fr", ...). */
export const language = (hass) =>
  String(hass?.locale?.language ?? hass?.language ?? "en")
    .split("-")[0]
    .toLowerCase();

/** A translate function for `hass`'s language: t("teams", { n: 10 }). */
export function translator(hass) {
  const table = STRINGS[language(hass)] ?? STRINGS.en;
  return (key, values = {}) =>
    (table[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) =>
      String(values[name] ?? ""),
    );
}

